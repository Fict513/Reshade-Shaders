#!/usr/bin/env python3
"""Rebuild the suite's algorithm includes from the preserved standalone shaders.

The explicit transformations keep the integration diff auditable. Run from any
directory; --check verifies that the checked-in includes are up to date.
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHADERS = ROOT / "Shaders"
OUT = SHADERS / "IPS_Suite"


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f"Expected exactly one occurrence of {old[:80]!r}")
    return text.replace(old, new, 1)


def between(text, start, end, replacement=""):
    if text.count(start) != 1:
        raise ValueError(f"Ambiguous markers: {start!r}, {end!r}")
    before, rest = text.split(start, 1)
    if end not in rest:
        raise ValueError(f"Missing end marker: {end!r}")
    _, after = rest.split(end, 1)
    return before + replacement + end + after


def module(filename, prefix, category):
    text = (SHADERS / filename).read_text()
    text = text[text.index("#ifndef "):text.index("\ntechnique ")]
    text = re.sub(r'ui_category = "[^"]+"', f'ui_category = "{category}"', text)
    return text


def rename_uniforms(text, prefix):
    names = re.findall(r"\buniform\s+\w+\s+(\w+)\s*<", text)
    for name in sorted(names, key=len, reverse=True):
        text = re.sub(rf"\b{name}\b", prefix + name, text)
    return text


def contrast():
    text = module("IPS_Depth_v2.fx", "Contrast", "1. Contrast")
    text = between(text, "uniform float Sharpen <", "texture2D InputTexture : COLOR;",
                   "static const float Sharpen = 0.0;\n"
                   "static const bool SplitView = false;\n"
                   "static const float SplitPosition = 0.5;\n"
                   "static const int View = 0;\n\n")
    text = between(text, "texture2D InputTexture : COLOR;",
                   "#if !_IPSD2_HDR && IPSD2_LOCAL")
    text = text.replace("InputSampler", "IPSSuite::OriginalSampler")
    text = between(text, "float Hash(float2 p)", "float4 Composite(")
    text = between(text, "    if (Dither > 0.0 && DitherStep() > 0.0)",
                   "    return float4(lerp(original.rgb, saturate(result), Strength), original.a);")
    return rename_uniforms(text, "Contrast")


def deband():
    text = module("Selective_Deband.fx", "Deband", "2. Debanding")
    text = between(text, "uniform float Dither <", "texture2D InputTexture : COLOR;",
                   "static const bool SplitView = false;\n"
                   "static const float SplitPosition = 0.5;\n"
                   "static const int View = 0;\n\n")
    text = between(text, "texture2D InputTexture : COLOR;", "float Luma(")
    text = text.replace("InputSampler", "_SUITE_DEBAND_INPUT")
    text = between(text, "float RectangleMask(", "void VS(",
                   "float HUDMask(float2 uv) { return 0.0; }\n")
    text = replace_once(text,
        "float4 PS(float4 position : SV_Position,float2 uv : TEXCOORD0) : SV_Target\n{\n",
        "float4 Process(float4 position, float2 uv, out float ditherEligibility)\n"
        "{\n    ditherEligibility = 0.0;\n")
    text = between(text, "#if SDB_DITHER\n    if (Dither>0.0",
                   "    return float4(saturate(result),original.a);",
                   "#if IPS_SUITE_DITHER\n"
                   "    ditherEligibility = smoothstep(0.0,0.25,eligible)*Strength"
                   "*smoothstep(0.01*step8,0.25*step8,change);\n"
                   "#endif\n")
    return rename_uniforms(text, "Deband")


def clarity():
    text = module("Adaptive_Clarity.fx", "Clarity", "3. Clarity")
    text = between(text, "uniform bool Mask1Enabled <", "texture2D InputTexture : COLOR;",
                   "static const bool SplitView = false;\n"
                   "static const float SplitPosition = 0.5;\n"
                   "static const int View = 0;\n\n")
    text = between(text, "texture2D InputTexture : COLOR;", "#if !_AC_HDR")
    text = text.replace("InputSampler", "_SUITE_CLARITY_INPUT")
    text = between(text, "float RectangleMask(", "#if !_AC_HDR",
                   "float HUDMask(float2 uv) { return 0.0; }\n")
    return rename_uniforms(text, "Clarity")


HEADER = """/*
IPS Suite algorithm module, derived from the corresponding standalone shader.
Copyright (c) 2026 OpenAI. MIT license; see LICENSE distributed with this suite.
Generated by validation/generate_ips_suite_includes.py; edit the generator or
standalone source rather than this file.
*/
"""


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    modules = {"Contrast.fxh": contrast(), "Deband.fxh": deband(),
               "Clarity.fxh": clarity()}
    if not args.check:
        OUT.mkdir(exist_ok=True)
    for name, content in modules.items():
        path = OUT / name
        expected = HEADER + content + "\n"
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f"Out of date: {path}")
        else:
            path.write_text(expected)
    print("IPS Suite algorithm includes " + ("verified" if args.check else "generated"))


if __name__ == "__main__":
    main()
